"""Build pc.html (the computer page) from index.html (the phone page).

The two pages are identical except that the computer page:
  * marks itself with data-engine="full" on <html>, so the app loads the full multi-threaded engine;
  * loads js/coi.js first, which registers the service worker that makes multi-threading possible.

Run after every change to index.html:  python tools/make_pc_page.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def build_pc_page(index_html: str) -> str:
    """Return the computer page's HTML given the phone page's HTML.

    Raises ValueError if index.html no longer has the markers this script edits.
    """
    html_tag = '<html lang="th">'
    title = "<title>Chess Review</title>"
    if html_tag not in index_html or title not in index_html:
        raise ValueError("index.html changed: update the markers in tools/make_pc_page.py")
    page = index_html.replace(html_tag, '<html lang="th" data-engine="full">', 1)
    page = page.replace(
        title,
        "<title>Chess Review (PC)</title>\n<script src=\"js/coi.js\"></script>",
        1,
    )
    # The notice goes after the doctype: a comment before it would put the page in quirks mode.
    doctype = "<!doctype html>\n"
    if not page.startswith(doctype):
        raise ValueError("index.html must start with <!doctype html>")
    notice = "<!-- Generated by tools/make_pc_page.py from index.html. Do not edit by hand. -->\n"
    return doctype + notice + page[len(doctype):]


def main() -> None:
    """Write pc.html next to index.html."""
    index_html = (ROOT / "index.html").read_text(encoding="utf-8")
    (ROOT / "pc.html").write_text(build_pc_page(index_html), encoding="utf-8", newline="\n")
    print("pc.html written")


if __name__ == "__main__":
    main()
